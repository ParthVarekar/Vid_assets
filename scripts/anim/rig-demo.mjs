// Gate 2 rig demo (6.5 s): every part of the rig in one short scene.
//   node scripts/anim/rig-demo.mjs   -> content/episodes/rig-demo.anim.json
// Chalk is bursting with excitement, Ink is not impressed, Quill is delighted.
// (Re-running overwrites hand edits made in Puppet Studio.)

import { ClipBuilder, EASE } from "./authoring.mjs";

const c = new ClipBuilder({
  name: "rig-demo",
  duration: 195,
  cast: ["quill", "ink", "chalk"],
  notes: "Gate 2 rig demo: hops, walk, talk, wave, expressions, follow-through. Generated by scripts/anim/rig-demo.mjs.",
});
c.home();
c.key("chalk", "x", 0, 1.95); // Chalk starts further out so she can waddle over

// Camera: wide lineup, slow push in.
c.camera(0, { px: 0.15, py: 1.05, pz: 9.8, tx: 0.15, ty: 0.62, tz: 0, fov: 22 }, EASE.inOut);
c.camera(195, { px: 0.3, py: 1.0, pz: 8.6, tx: 0.25, ty: 0.64, tz: 0, fov: 22 });

// ---- Chalk: excited double hop, waddle over, chatter and wave -------------
c.pose("chalk", 8, { lookX: 0, pupil: 1, lidOpen: 0 }, EASE.inOut);
c.pose("chalk", 14, { pupil: 1.28, lidOpen: 0.45, squint: 0.25 }, EASE.snap);
c.hop("chalk", 18, { height: 0.55, wings: 0.9 });
c.hop("chalk", 52, { height: 0.42, wings: 0.8 });
c.pose("chalk", 72, { lookX: -0.7 }, EASE.snap); // looks at Quill
c.pose("chalk", 80, { yaw: 0 }, EASE.inOut);
c.pose("chalk", 86, { yaw: -66 }, EASE.inOut);
c.walk("chalk", { f0: 86, f1: 128, x0: 1.95, x1: 1.3, yaw: -66, stride: 0.13, waddle: 7 });
c.pose("chalk", 128, { yaw: -66 }, EASE.inOut);
c.pose("chalk", 136, { yaw: -24, lookX: -0.35 }, EASE.inOut);
c.say("chalk", 134, 164, 1.1);
c.keys("chalk", "wingR", [[132, 0, EASE.out], [138, 0.95, EASE.inOut]]);
for (let f = 138, i = 0; f < 164; f += 5, i++) c.key("chalk", "wingSwingR", f, i % 2 ? -0.35 : 0.35, EASE.inOut);
c.keys("chalk", "wingSwingR", [[164, 0, EASE.inOut]]);
c.keys("chalk", "wingR", [[164, 0.95, EASE.inOut], [172, 0, EASE.inOut]]);
c.pose("chalk", 164, { squint: 0.25, lidOpen: 0.45 }, EASE.inOut);
c.pose("chalk", 174, { squint: 0.55, lidOpen: 0.1, tilt: -8, lidTiltL: 0.2, lidTiltR: 0.2 }, EASE.inOut);

// ---- Quill: notices, curious, delighted, cheers ----------------------------
c.pose("quill", 20, { lookX: 0, tilt: 0, lean: 0 }, EASE.snap);
c.pose("quill", 24, { lookX: 0.85, lookY: 0.15 }, EASE.inOut);
c.keys("quill", "blinkL", [[21, 0, EASE.inOut], [23, 0.9, EASE.inOut], [26, 0, EASE.inOut]]);
c.keys("quill", "blinkR", [[21, 0, EASE.inOut], [23, 0.9, EASE.inOut], [26, 0, EASE.inOut]]);
c.pose("quill", 34, { tilt: 11, lean: 5, lidTiltL: 0.25, lidTiltR: 0.25, lidOpen: 0.2 }, EASE.inOut);
c.pose("quill", 58, { tilt: 11, lean: 5, lidOpen: 0.2, squint: 0, pupil: 1, beakOpen: 0 }, EASE.inOut);
c.pose("quill", 66, { tilt: 4, lean: 0, lidOpen: 0, squint: 0.55, pupil: 1.2, beakOpen: 0.3, lidTiltL: 0.3, lidTiltR: 0.3 }, EASE.overshoot);
c.pose("quill", 126, { twist: 0, lookX: 0.85, beakOpen: 0.3 }, EASE.inOut);
c.pose("quill", 134, { twist: 16, lookX: 0.45, beakOpen: 0.15 }, EASE.inOut);
c.pose("quill", 150, { wingL: 0, wingR: 0, squint: 0.55 }, EASE.anticipate);
c.hop("quill", 156, { height: 0.26, wings: 0, squash: 0.2 });
c.pose("quill", 156, { wingL: 1.1, wingR: 1.1, squint: 0.75, beakOpen: 0.55, crest: 0.3 }, EASE.inOut);
c.pose("quill", 180, { wingL: 0.15, wingR: 0.15, beakOpen: 0.25, crest: 0 }, EASE.inOut);

// ---- Ink: watches, sceptical, head shake, relents with a smug blink --------
c.pose("ink", 24, { lookX: 0 }, EASE.inOut);
c.pose("ink", 30, { lookX: 0.65 }, EASE.inOut);
c.pose("ink", 38, { lidTiltL: 0, lidTiltR: 0, blinkL: 0, squint: 0, lean: 0 }, EASE.inOut);
c.pose("ink", 46, { lidTiltL: -0.6, lidTiltR: 0.3, blinkL: 0.3, squint: 0.25, lean: -6 }, EASE.snap);
c.pose("ink", 72, { lookX: 0.65 }, EASE.inOut);
c.pose("ink", 76, { lookX: 0 }, EASE.inOut);
c.shake("ink", "twist", 78, { amp: 9, n: 4, every: 4 });
c.pose("ink", 96, { lookX: 0.5 }, EASE.inOut);
c.pose("ink", 152, { lidTiltL: -0.6, lidTiltR: 0.3, blinkL: 0.3, squint: 0.25, tilt: 0, lean: -6 }, EASE.inOut);
c.pose("ink", 162, { lidTiltL: -0.15, lidTiltR: -0.15, blinkL: 0.15, squint: 0.4, tilt: -7, lean: 0 }, EASE.inOut);
c.keys("ink", "autoBlink", [[0, 1, "step"], [166, 0, "step"]]);
c.keys("ink", "blinkR", [[170, 0, EASE.in], [176, 1, EASE.inOut], [183, 0.15, EASE.out]]);
c.keys("ink", "blinkL", [[170, 0.15, EASE.in], [176, 1, EASE.inOut], [183, 0.3, EASE.out]]);

console.log("wrote", c.write());
